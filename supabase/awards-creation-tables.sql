-- ─────────────────────────────────────────────────────────────
-- 1. Les tables
-- ─────────────────────────────────────────────────────────────
create table if not exists public.awards_config (
  id      integer primary key default 1,
  ouvert  boolean not null default false,
  fin     timestamptz,
  phase   text not null default 'avant',
  maj_le  timestamptz default now()
);

create table if not exists public.awards_cands (
  id        bigint generated by default as identity primary key,
  user_id   uuid not null default auth.uid(),
  fan_id    text,
  pseudo    text,
  categorie text not null,
  nom       text,
  detail    text,
  contenu   text,
  lien      text,
  valide    boolean not null default false,
  rejete    boolean not null default false,
  cree_le   timestamptz default now()
);

create table if not exists public.awards_votes (
  id        bigint generated by default as identity primary key,
  user_id   uuid not null default auth.uid(),
  categorie text not null,
  jour      text not null,
  cand_id   bigint not null,
  cree_le   timestamptz default now()
);

-- ─────────────────────────────────────────────────────────────
-- 1 bis. Si les tables existaient déjà (c'est ton cas), on complète
--        les colonnes qui manquent. « create table if not exists »
--        ne les aurait pas ajoutées tout seul.
-- ─────────────────────────────────────────────────────────────
alter table public.awards_config add column if not exists ouvert boolean default false;
alter table public.awards_config add column if not exists fin    timestamptz;
alter table public.awards_config add column if not exists phase  text;
alter table public.awards_config add column if not exists maj_le timestamptz default now();
update public.awards_config set phase = 'avant' where phase is null;
alter table public.awards_config alter column phase set default 'avant';

alter table public.awards_cands add column if not exists user_id   uuid;
alter table public.awards_cands add column if not exists fan_id    text;
alter table public.awards_cands add column if not exists pseudo    text;
alter table public.awards_cands add column if not exists categorie text;
alter table public.awards_cands add column if not exists nom       text;
alter table public.awards_cands add column if not exists detail    text;
alter table public.awards_cands add column if not exists contenu   text;
alter table public.awards_cands add column if not exists lien      text;
alter table public.awards_cands add column if not exists valide    boolean default false;
alter table public.awards_cands add column if not exists rejete    boolean default false;
alter table public.awards_cands add column if not exists cree_le   timestamptz default now();

alter table public.awards_votes add column if not exists user_id   uuid;
alter table public.awards_votes add column if not exists categorie text;
alter table public.awards_votes add column if not exists jour      text;
alter table public.awards_votes add column if not exists cand_id   bigint;
alter table public.awards_votes add column if not exists cree_le   timestamptz default now();

-- un seul vote par personne, par catégorie et par jour (verrou côté base)
create unique index if not exists awards_votes_unique
  on public.awards_votes (user_id, categorie, jour);

create index if not exists awards_cands_cat on public.awards_cands (categorie);

-- la ligne de réglages (une seule)
insert into public.awards_config (id, ouvert, phase)
values (1, false, 'avant')
on conflict (id) do nothing;

-- ─────────────────────────────────────────────────────────────
-- 2. Qui est la modératrice
-- ─────────────────────────────────────────────────────────────
create or replace function public.est_moderatrice()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'elisabeth.sikora@orange.fr';
$$;

grant execute on function public.est_moderatrice() to anon, authenticated;

-- ─────────────────────────────────────────────────────────────
-- 3. Les règles de sécurité
-- ─────────────────────────────────────────────────────────────
alter table public.awards_config enable row level security;
alter table public.awards_cands  enable row level security;
alter table public.awards_votes  enable row level security;

-- Réglages : tout le monde lit, seule la modératrice modifie
drop policy if exists awards_config_lecture on public.awards_config;
create policy awards_config_lecture on public.awards_config
  for select using (true);

drop policy if exists awards_config_ecriture on public.awards_config;
create policy awards_config_ecriture on public.awards_config
  for all using (public.est_moderatrice()) with check (public.est_moderatrice());

-- Candidatures : on ne voit que celles qui sont validées
--                (plus les siennes, plus tout pour la modératrice)
drop policy if exists awards_cands_lecture on public.awards_cands;
create policy awards_cands_lecture on public.awards_cands
  for select using (
    (valide = true and rejete = false)
    or auth.uid() = user_id
    or public.est_moderatrice()
  );

-- Chacun peut proposer une candidature, à son nom
drop policy if exists awards_cands_insert on public.awards_cands;
create policy awards_cands_insert on public.awards_cands
  for insert to authenticated with check (auth.uid() = user_id);

-- Seule la modératrice valide, rejette ou retire
drop policy if exists awards_cands_update on public.awards_cands;
create policy awards_cands_update on public.awards_cands
  for update using (public.est_moderatrice()) with check (public.est_moderatrice());

drop policy if exists awards_cands_delete on public.awards_cands;
create policy awards_cands_delete on public.awards_cands
  for delete using (public.est_moderatrice());

-- Votes : chacun ne voit que les siens (résultats secrets),
--         la modératrice voit tout pour préparer la cérémonie
drop policy if exists awards_votes_lecture on public.awards_votes;
create policy awards_votes_lecture on public.awards_votes
  for select using (auth.uid() = user_id or public.est_moderatrice());

drop policy if exists awards_votes_insert on public.awards_votes;
create policy awards_votes_insert on public.awards_votes
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists awards_votes_update on public.awards_votes;
create policy awards_votes_update on public.awards_votes
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists awards_votes_delete on public.awards_votes;
create policy awards_votes_delete on public.awards_votes
  for delete using (auth.uid() = user_id);

-- ─────────────────────────────────────────────────────────────
-- 3 bis. Le jour du vote est décidé par le serveur, pas par le
--        téléphone du votant : impossible de revoter en changeant
--        la date de son appareil.
-- ─────────────────────────────────────────────────────────────
create or replace function public.awards_jour_serveur()
returns trigger
language plpgsql
as $$
begin
  new.jour := to_char((now() at time zone 'utc')::date, 'YYYY-MM-DD');
  return new;
end;
$$;

drop trigger if exists awards_votes_jour on public.awards_votes;
create trigger awards_votes_jour
  before insert or update on public.awards_votes
  for each row execute function public.awards_jour_serveur();

-- ─────────────────────────────────────────────────────────────
-- 4. Les totaux officiels : donnés par le serveur
--    uniquement le jour de la cérémonie (ou à la modératrice)
-- ─────────────────────────────────────────────────────────────
create or replace function public.awards_resultats()
returns table(cand_id bigint, votes bigint)
language sql
security definer
set search_path = public
as $$
  select v.cand_id, count(*)::bigint
  from public.awards_votes v
  where (select coalesce(c.phase, '') from public.awards_config c where c.id = 1) = 'ceremonie'
     or public.est_moderatrice()
  group by v.cand_id;
$$;

grant execute on function public.awards_resultats() to anon, authenticated;

-- combien de votes chaque fan a déposés (pour ses points) — sans jamais
-- révéler POUR QUI il a voté
create or replace function public.awards_votes_par_fan()
returns table(user_id uuid, n bigint)
language sql
security definer
set search_path = public
as $$
  select v.user_id, count(*)::bigint from public.awards_votes v group by v.user_id;
$$;

grant execute on function public.awards_votes_par_fan() to anon, authenticated;

